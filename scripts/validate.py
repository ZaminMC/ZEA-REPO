#!/usr/bin/env python3
"""Validate ZEA-REPO data files against their JSON schemas.

Usage:
    python3 scripts/validate.py                    # validate everything
    python3 scripts/validate.py --update-manifest   # regenerate manifest.json

Validation rules:
  - Every .json file under datasets/ must parse and conform to the schema
    selected by its path.
  - Files outside the known dataset locations are rejected.
  - manifest.json must conform to its schema, list only existing files, and
    record correct sha256 hashes.

The manifest is generated by this script (and by CI on merges to main);
it is never edited by hand.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
from datetime import datetime, timezone
from pathlib import Path

try:
    import jsonschema
except ImportError:  # pragma: no cover
    print("error: the 'jsonschema' package is required (pip install jsonschema)")
    sys.exit(2)

REPO_ROOT = Path(__file__).resolve().parent.parent

# Dataset location rules: (glob pattern relative to repo root, schema path).
DATASET_RULES = [
    ("datasets/badges.json", "schemas/badges.schema.json"),
    ("datasets/channels.json", "schemas/channels.schema.json"),
    ("datasets/nations/*.json", "schemas/nation.schema.json"),
    ("datasets/towns/*.json", "schemas/town.schema.json"),
]

MANIFEST_PATH = Path("manifest.json")
MANIFEST_SCHEMA_PATH = Path("schemas/manifest.schema.json")


def load_json(path: Path):
    with path.open(encoding="utf-8") as fh:
        return json.load(fh)


def sha256_of(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def schema_for(rel_path: str) -> str | None:
    for pattern, schema in DATASET_RULES:
        if Path(rel_path).match(pattern):
            return schema
    return None


def dataset_id_for(rel_path: str) -> str:
    """Group a file under a dataset id: top-level files use their stem,
    per-entity directories use the directory name."""
    parts = Path(rel_path).parts  # ("datasets", "nations", "x.json")
    if len(parts) == 2:
        return parts[1].removesuffix(".json")
    return parts[1]


def validate_datasets(errors: list[str]) -> dict[str, dict[str, str]]:
    """Validate every dataset file; return the computed manifest index."""
    index: dict[str, dict[str, str]] = {}
    dataset_files = sorted((REPO_ROOT / "datasets").rglob("*.json"))
    known_paths = set()

    for file in dataset_files:
        rel = file.relative_to(REPO_ROOT).as_posix()
        known_paths.add(rel)
        schema_path = schema_for(rel)
        if schema_path is None:
            errors.append(f"{rel}: not a recognized dataset location")
            continue
        try:
            document = load_json(file)
        except json.JSONDecodeError as exc:
            errors.append(f"{rel}: invalid JSON ({exc})")
            continue
        schema = load_json(REPO_ROOT / schema_path)
        validator = jsonschema.Draft202012Validator(
            schema, format_checker=jsonschema.FormatChecker()
        )
        for issue in sorted(validator.iter_errors(document), key=str):
            errors.append(f"{rel}: {issue.message} at {list(issue.path)}")
        dataset = dataset_id_for(rel)
        index.setdefault(dataset, {})[rel] = sha256_of(file)
    return index


def validate_manifest(errors: list[str]) -> None:
    manifest_file = REPO_ROOT / MANIFEST_PATH
    if not manifest_file.exists():
        errors.append("manifest.json: missing (run scripts/validate.py --update-manifest)")
        return
    try:
        manifest = load_json(manifest_file)
    except json.JSONDecodeError as exc:
        errors.append(f"manifest.json: invalid JSON ({exc})")
        return
    schema = load_json(REPO_ROOT / MANIFEST_SCHEMA_PATH)
    validator = jsonschema.Draft202012Validator(
        schema, format_checker=jsonschema.FormatChecker()
    )
    for issue in sorted(validator.iter_errors(manifest), key=str):
        errors.append(f"manifest.json: {issue.message} at {list(issue.path)}")

    for dataset, entry in manifest.get("datasets", {}).items():
        for rel, digest in entry.get("files", {}).items():
            path = REPO_ROOT / rel
            if not path.exists():
                errors.append(f"manifest.json: {rel} listed but missing")
            elif sha256_of(path) != digest:
                errors.append(f"manifest.json: stale hash for {rel}")


def build_manifest(index: dict[str, dict[str, str]]) -> dict:
    return {
        "format": "zea-repo/manifest",
        "version": 1,
        "generated": datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "datasets": {
            dataset: {"files": dict(sorted(files.items()))}
            for dataset, files in sorted(index.items())
        },
    }


def write_manifest(index: dict[str, dict[str, str]]) -> None:
    manifest = build_manifest(index)
    target = REPO_ROOT / MANIFEST_PATH
    with target.open("w", encoding="utf-8", newline="\n") as fh:
        json.dump(manifest, fh, indent=2, ensure_ascii=False)
        fh.write("\n")
    print(f"manifest.json: updated ({sum(len(v) for v in index.values())} files)")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--update-manifest",
        action="store_true",
        help="regenerate manifest.json from the current dataset files",
    )
    args = parser.parse_args()

    errors: list[str] = []
    index = validate_datasets(errors)

    if args.update_manifest:
        write_manifest(index)
        errors = []  # re-derive: manifest was just rewritten
        validate_manifest(errors)
    else:
        validate_manifest(errors)

    if errors:
        print(f"\n{len(errors)} error(s):")
        for error in errors:
            print(f"  - {error}")
        return 1
    print("OK: all files valid")
    return 0


if __name__ == "__main__":
    sys.exit(main())
